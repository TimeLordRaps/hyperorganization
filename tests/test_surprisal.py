"""Price without money: the cost of compromising something is the surprisal of doing it.

hyperethics prices a party by what an attacker pays to bring it under control and a gate by
the cheapest total price of a set of parties that together control it. Nothing in that
machinery needs money. It needs a quantity that ADDS across things an attacker must do
together and that a cheaper way beats a dearer one. Surprisal does both when the events are
independent:

    bits(p) = -log2 p        P(A and B) = P(A) P(B)   <=>   bits(A and B) = bits(A) + bits(B)

so the cheapest cover of a gate, read in bits, is the MOST PROBABLE way to take it.

What is checked here
    * the arithmetic of bits, including probabilities too small for a float;
    * gate cost in bits against an independent brute force, and against the numbers
      hyperethics itself computes (a golden file regenerated by scripts/regenerate_golden.py;
      this package never imports hyperethics);
    * that the number means what it says: the probability of taking the gate is at least
      2**-cost (the cheapest cover is one way in) and at most the number of minimal covers
      times that (a union bound), exact rationals both, against an inclusion-exclusion oracle;
    * a council of m seats that needs q has price -log2 T(x), about q bits per seat minus
      log2 C(m, q) when seats are dear;
    * where additivity breaks: a common principal makes the joint surprisal of its seats
      smaller than the sum of their marginals, by exactly the discount hyperethics sees as
      the `common-principal` cause.
"""

