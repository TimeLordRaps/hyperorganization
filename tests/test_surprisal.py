# --- what the cost means: a probability, bracketed ------------------------------------------------------


def inclusion_exclusion(probs, covers):
    """P(some minimal cover has all its roots compromised), by inclusion-exclusion. No shared code."""
    total = F(0)
    for size in range(1, len(covers) + 1):
        for chosen in combinations(covers, size):
            union = frozenset().union(*chosen)
            term = F(1)
            for root in union:
                term *= probs[root]
            total += (-1) ** (size + 1) * term
    return total


def test_the_probability_of_taking_a_gate_is_exact_and_matches_inclusion_exclusion():
    rng = random.Random(54)
    checked = 0
    while checked < 120:
        names, controls, _p, need = random_net(rng, rng.randint(2, 6))
        probs = {n: F(rng.randint(0, 8), 8) for n in names}
        covers = brute_force_covers(names, controls, need)
        minimal = [c for c in covers if not any(d < c for d in covers)]
        if len(minimal) > 9:
            continue
        assert S.capture_probability_gate(probs, controls, need) == inclusion_exclusion(probs, minimal)
        checked += 1


def test_the_cost_brackets_the_probability_within_the_number_of_minimal_covers():
    rng = random.Random(55)
    checked = 0
    while checked < 200:
        names, controls, _p, need = random_net(rng, rng.randint(2, 6))
        bits = {n: rng.choice([0, 1, 2, 3, 4]) for n in names}
        probs = {n: F(1, 2 ** bits[n]) for n in names}
        lower, exact, upper = S.sandwich_gate(probs, controls, need)
        covers = S.minimal_covers(names, controls, need)
        cost = S.gate_bits(bits, controls, need)
        assert lower == F(1, 2 ** int(cost))  # the cheapest cover alone: 2^-cost
        assert lower <= exact <= upper <= 1
        assert upper <= len(covers) * lower  # every cover is at most as probable as the best one
        checked += 1


def test_a_gate_with_one_cheapest_cover_is_taken_with_probability_close_to_two_to_minus_its_cost():
    probs = {"A": F(1, 2**12), "B": F(1, 2**12)}
    lower, exact, upper = S.sandwich_gate(probs, set(), frozenset({"A", "B"}))
    assert lower == exact == upper == F(1, 2**24)


# --- the numbers hyperethics computes --------------------------------------------------------------------


def golden_cases():
    for system in GOLDEN["systems"]:
        for power, gate in system["gates"].items():
            yield pytest.param(system, power, gate, id=f"{system['name']}:{power}")


def decode(value):
    return math.inf if value == "inf" else value


@pytest.mark.parametrize("system,power,gate", list(golden_cases()))
def test_gate_bits_reproduces_what_hyperethics_computes(system, power, gate):
    prices = {name: decode(price) for name, price in system["parties"].items()}
    controls = {tuple(edge) for edge in system["controls"]}
    assert S.gate_bits(prices, controls, frozenset(gate["need"])) == decode(gate["gate_cost"])


def test_the_golden_file_has_teeth_ignoring_command_changes_the_answer_where_it_should():
    changed = []
    for system in GOLDEN["systems"]:
        prices = {name: decode(price) for name, price in system["parties"].items()}
        for power, gate in system["gates"].items():
            blind = S.gate_bits(prices, set(), frozenset(gate["need"]))
            if blind != decode(gate["gate_cost"]):
                changed.append((system["name"], power))
    # exactly the systems whose cheapest cover runs through a command edge into the gate
    assert {name for name, _ in changed} == {"common-principal", "client-state", "shadow-court"}


def test_the_golden_file_names_the_hyperethics_commit_it_came_from():
    assert len(GOLDEN["hyperethics_commit"]) == 40
    assert "scripts/regenerate_golden.py" in GOLDEN["command"]


@pytest.mark.parametrize("system", [s for s in GOLDEN["systems"] if all(
    decode(v) != math.inf for v in s["parties"].values())], ids=lambda s: s["name"])
def test_every_golden_gate_is_a_probability_bracketed_by_its_cost(system):
    names = list(system["parties"])
    controls = {tuple(edge) for edge in system["controls"]}
    probs = {n: F(1, 2 ** int(system["parties"][n])) for n in names}
    for gate in system["gates"].values():
        need = frozenset(gate["need"])
        lower, exact, upper = S.sandwich_gate(probs, controls, need)
        assert lower == F(1, 2 ** int(gate["gate_cost"]))
        assert lower <= exact <= upper


# --- councils and blocks ------------------------------------------------------------------------------------


def enumerated_capture(blocks, q):
    total = F(0)
    for mask in range(1 << len(blocks)):
        weight, prob = 0, F(1)
        for i, block in enumerate(blocks):
            if mask >> i & 1:
                weight += block.weight
                prob *= block.probability
            else:
                prob *= 1 - block.probability
        if weight >= q:
            total += prob
    return total


def random_blocks(rng, n=None):
    n = n or rng.randint(1, 8)
    return [S.Block(f"b{i}", F(rng.randint(0, 10), 10), rng.randint(1, 3)) for i in range(n)]


def test_capture_probability_of_blocks_is_the_sum_over_every_outcome():
    rng = random.Random(56)
    for _ in range(300):
        blocks = random_blocks(rng)
        q = rng.randint(0, sum(b.weight for b in blocks) + 1)
        assert S.capture_probability(blocks, q) == enumerated_capture(blocks, q)


def test_equal_unit_blocks_are_the_quorum_map():
    for m in range(1, 9):
        for q in range(0, m + 2):
            x = F(1, 3)
            blocks = [S.Block(f"s{i}", x, 1) for i in range(m)]
            assert S.capture_probability(blocks, q) == Q.tail(m, q, x)


def test_the_cheapest_capture_is_the_most_probable_winning_coalition_by_brute_force():
    rng = random.Random(57)
    for _ in range(200):
        blocks = random_blocks(rng, rng.randint(1, 8))
        q = rng.randint(1, sum(b.weight for b in blocks))
        best = None
        for size in range(len(blocks) + 1):
            for chosen in combinations(blocks, size):
                if sum(b.weight for b in chosen) >= q:
                    cost = sum(S.bits(b.probability) for b in chosen)
                    best = cost if best is None else min(best, cost)
        cost, names = S.cheapest_capture(blocks, q)
        assert cost == pytest.approx(best, abs=1e-9) or (cost == best == math.inf)
        if cost != math.inf:
            assert sum(b.weight for b in blocks if b.name in names) >= q


def test_a_quorum_nobody_can_reach_has_no_capture():
    blocks = [S.Block("a", F(1, 2), 1), S.Block("b", F(1, 2), 1)]
    assert S.cheapest_capture(blocks, 3) == (math.inf, ())
    assert S.capture_probability(blocks, 3) == 0


def test_blocks_bracket_the_capture_probability_like_gates_do():
    rng = random.Random(58)
    for _ in range(200):
        blocks = random_blocks(rng, rng.randint(1, 7))
        q = rng.randint(1, sum(b.weight for b in blocks))
        lower, exact, upper = S.sandwich(blocks, q)
        assert lower <= exact <= upper <= 1


# --- where additivity breaks ----------------------------------------------------------------------------------


def test_a_common_principal_makes_the_joint_surprisal_less_than_the_sum_of_the_marginals():
    principal, own = F(1, 10), [F(1, 100)] * 3
    joint, independent = S.common_principal_joint(principal, own)
    assert joint == principal + (1 - principal) * F(1, 100) ** 3
    marginal = principal + (1 - principal) * F(1, 100)
    assert independent == marginal**3
    assert joint > independent
    gap = S.additivity_gap(principal, own)
    assert gap == pytest.approx(S.bits(independent) - S.bits(joint))
    assert gap > 6  # about 6.3 bits: three seats that look 3.2 bits each cost the attacker 3.3 in all


def test_without_a_principal_the_seats_are_independent_and_the_gap_is_zero():
    assert S.additivity_gap(F(0), [F(1, 10), F(1, 5), F(1, 3)]) == pytest.approx(0.0, abs=1e-12)


def test_the_gap_grows_with_the_number_of_seats_one_principal_commands():
    gaps = [S.additivity_gap(F(1, 10), [F(1, 100)] * k) for k in range(1, 7)]
    assert gaps[0] == pytest.approx(0.0, abs=1e-12)  # one seat: nothing to share
    assert all(a < b for a, b in zip(gaps, gaps[1:]))


def test_a_common_principal_is_the_discount_hyperethics_prices_as_a_cheaper_cover():
    # hyperethics: A, B at 3 bits each, one Boss at 3 bits commanding both: the gate costs 3, not 6.
    prices = {"A": 3, "B": 3, "Boss": 3}
    together = S.gate_bits(prices, {("Boss", "A"), ("Boss", "B")}, frozenset({"A", "B"}))
    apart = S.gate_bits(prices, set(), frozenset({"A", "B"}))
    assert apart - together == 3


